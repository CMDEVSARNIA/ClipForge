import { apiError, json, type Env } from "./env.ts";

/**
 * App tokens are stateless and HMAC-signed: base64url(payload) + "." + base64url(hmac).
 * The payload carries the install id; revocation is a KV flag. Anyone holding the invite code can
 * register, so the code is the real gate; tokens just avoid sending the code on every request.
 */
export interface TokenPayload {
  iid: string; // install id (random UUID generated by the app)
  iat: number; // issued-at, epoch seconds
  v: 1;
}

const enc = new TextEncoder();

function b64url(bytes: ArrayBuffer | Uint8Array): string {
  const arr = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  let s = "";
  for (const b of arr) s += String.fromCharCode(b);
  return btoa(s).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

function fromB64url(s: string): Uint8Array {
  const pad = s.length % 4 === 0 ? "" : "=".repeat(4 - (s.length % 4));
  const bin = atob(s.replace(/-/g, "+").replace(/_/g, "/") + pad);
  return Uint8Array.from(bin, (c) => c.charCodeAt(0));
}

async function hmacKey(secret: string): Promise<CryptoKey> {
  return crypto.subtle.importKey("raw", enc.encode(secret), { name: "HMAC", hash: "SHA-256" }, false, ["sign", "verify"]);
}

export async function signToken(payload: TokenPayload, secret: string): Promise<string> {
  const body = b64url(enc.encode(JSON.stringify(payload)));
  const sig = await crypto.subtle.sign("HMAC", await hmacKey(secret), enc.encode(body));
  return `${body}.${b64url(sig)}`;
}

export async function verifyToken(token: string, secret: string): Promise<TokenPayload | null> {
  const parts = token.split(".");
  if (parts.length !== 2) return null;
  const [body, sig] = parts;
  let sigBytes: Uint8Array;
  try {
    sigBytes = fromB64url(sig);
  } catch {
    return null;
  }
  // crypto.subtle.verify compares in constant time.
  const ok = await crypto.subtle.verify("HMAC", await hmacKey(secret), sigBytes, enc.encode(body));
  if (!ok) return null;
  try {
    const p = JSON.parse(new TextDecoder().decode(fromB64url(body))) as TokenPayload;
    if (p.v !== 1 || typeof p.iid !== "string" || typeof p.iat !== "number") return null;
    return p;
  } catch {
    return null;
  }
}

/** Constant-time string equality via HMAC digests (equal length, no early exit). */
async function safeEqual(a: string, b: string, secret: string): Promise<boolean> {
  const key = await hmacKey(secret);
  const [da, db] = await Promise.all([
    crypto.subtle.sign("HMAC", key, enc.encode(a)),
    crypto.subtle.sign("HMAC", key, enc.encode(b)),
  ]);
  const x = new Uint8Array(da);
  const y = new Uint8Array(db);
  let diff = 0;
  for (let i = 0; i < x.length; i++) diff |= x[i] ^ y[i];
  return diff === 0;
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export async function handleRegister(req: Request, env: Env): Promise<Response> {
  const ip = req.headers.get("cf-connecting-ip") ?? "unknown";
  const { success } = await env.REGISTER_LIMITER.limit({ key: `reg:${ip}` });
  if (!success) return apiError(429, "rate_limit_error", "Too many registration attempts. Wait a minute.");

  let body: { invite_code?: unknown; install_id?: unknown };
  try {
    body = await req.json();
  } catch {
    return apiError(400, "invalid_request_error", "Body must be JSON.");
  }
  if (typeof body.invite_code !== "string" || typeof body.install_id !== "string" || !UUID_RE.test(body.install_id)) {
    return apiError(400, "invalid_request_error", "invite_code (string) and install_id (UUID) are required.");
  }
  if (!env.INVITE_CODE || !env.TOKEN_SIGNING_KEY) {
    return apiError(500, "api_error", "Worker is missing INVITE_CODE or TOKEN_SIGNING_KEY secrets.");
  }
  if (!(await safeEqual(body.invite_code.trim(), env.INVITE_CODE, env.TOKEN_SIGNING_KEY))) {
    return apiError(401, "authentication_error", "Invite code is wrong.");
  }
  const token = await signToken({ iid: body.install_id.toLowerCase(), iat: Math.floor(Date.now() / 1000), v: 1 }, env.TOKEN_SIGNING_KEY);
  return json({ token });
}

/** Returns the install id for a valid, non-revoked bearer token, or an error Response. */
export async function authenticate(req: Request, env: Env): Promise<{ iid: string } | Response> {
  const header = req.headers.get("authorization") ?? "";
  const m = /^Bearer\s+(.+)$/i.exec(header);
  if (!m) return apiError(401, "authentication_error", "Missing app token. Connect the app in Settings.");
  const payload = await verifyToken(m[1].trim(), env.TOKEN_SIGNING_KEY);
  if (!payload) return apiError(401, "authentication_error", "Invalid app token. Reconnect the app in Settings.");
  if (await env.KV.get(`revoked:${payload.iid}`)) {
    return apiError(401, "authentication_error", "This install was revoked.");
  }
  const { success } = await env.TOKEN_LIMITER.limit({ key: `tok:${payload.iid}` });
  if (!success) return apiError(429, "rate_limit_error", "Too many requests from this install. Slow down.", { "retry-after": "20" });
  return { iid: payload.iid };
}
